#!/bin/bash
# Build everything: the RAR->RAC transpiler (plexi), the RAC parser, the
# generated RAC and ACL2 sources, and certify all ACL2 books.
#
#   ./build.sh          full build
#   ./build.sh clean    remove all build outputs
set -euo pipefail
cd "$(dirname "$0")"
WORK=$(pwd)

ACL2_BIN=${ACL2:-$(command -v acl2)}
# Community books directory (contains projects/rac and rtl/rel11).
BOOKS=${ACL2_BOOKS:-/opt/acl2/books}
RACSRC=$BOOKS/projects/rac

if [[ "${1:-}" == "clean" ]]; then
  rm -rf build plexi/target
  rm -f gen/*.i gen/*.ast.pp gen/*.acl2.log
  find . \( -name '*.cert' -o -name '*.fasl' -o -name '*.port' -o -name '*.cert.out' \
            -o -name '*.cert.time' -o -name '*@expansion.lsp' -o -name 'Makefile-tmp' \) -delete
  exit 0
fi

# 1. The Plexi transpiler (RAR -> RAC), written in Rust, no external crates.
echo "== building plexi"
(cd plexi && cargo build --release --offline -q)
PLEXI=$WORK/plexi/target/release/plexi

# 2. The RAC parser, built from the RAC sources in the community books.
#    build/rac mirrors the layout of books/projects/rac (bin, lisp, include),
#    so the standard `rac` driver script works unchanged.
echo "== building the RAC parser from $RACSRC"
mkdir -p build/rac/bin
if [[ ! -x build/rac/bin/parse ]]; then
  rm -rf build/rac-src
  cp -r "$RACSRC/src" build/rac-src
  make -s -C build/rac-src RAC="$WORK/build/rac" ACL2="$ACL2_BIN" all
fi
ln -sfn "$RACSRC/lisp" build/rac/lisp
ln -sfn "$RACSRC/include" build/rac/include
RAC=$WORK/build/rac/bin/rac

# 3. RAR -> RAC -> ACL2.  Two instances of the same RAR program:
#      gen/arrayset   ARR_SZ = 1024 (as in the paper's source)
#      gen/arrayset6  ARR_SZ = 6    (the example of Figure 4)
mkdir -p gen
gen() {   # gen NAME [plexi options]
  local name=$1; shift
  echo "== plexi: src/arrayset.rs -> gen/$name.cpp $*"
  "$PLEXI" src/arrayset.rs "gen/$name.cpp" "$@"
  # The generated RAC must be ordinary C++ as well.
  g++ -std=c++14 -fsyntax-only -I "$RACSRC/include" "gen/$name.cpp"
  echo "== rac -a gen/$name.cpp -> gen/$name.lisp"
  (cd gen && "$RAC" -a "$name.cpp")
}
gen arrayset
gen arrayset6 -D ARR_SZ=6

# 4. The verification books are written once, against gen/arrayset
#    (ARR_SZ = 1024).  The proofs never look at the value of ARR_SZ (they
#    only use 1 < ARR_SZ < 2^32), so the same books are instantiated for
#    gen/arrayset6 (ARR_SZ = 6) by renaming the included books.
for b in defs thms invariants; do
  { echo "; GENERATED by build.sh from arrayset-$b.lisp -- do not edit."
    echo "; The same definitions and proofs, for the ARR_SZ = 6 instance."
    sed -e 's|(include-book "gen/arrayset")|(include-book "gen/arrayset6")|' \
        -e 's|(include-book "arrayset-defs")|(include-book "arrayset6-defs")|' \
        -e 's|(include-book "arrayset-thms")|(include-book "arrayset6-thms")|' \
        "arrayset-$b.lisp"
  } > "arrayset6-$b.lisp"
done

# 5. Certify all books.
echo "== cert.pl"
cert.pl --acl2 "$ACL2_BIN" -j "${JOBS:-4}" gen/arrayset.lisp gen/arrayset6.lisp \
  arrayset-defs.lisp arrayset-thms.lisp arrayset-invariants.lisp \
  arrayset6-defs.lisp arrayset6-thms.lisp arrayset6-invariants.lisp \
  examples.lisp
echo "== done"
