%% erl_to_acl2: Erlang front end for the ACL2 CPS evaluator.
%%
%% Uses the standard OTP front end (epp / erl_scan / erl_parse) to obtain
%% Erlang abstract syntax trees, normalizes them, and prints them as ACL2
%% s-expressions (see README.md for the AST grammar).
%%
%% Usage (as an escript):
%%   escript erl_to_acl2.erl FILE.erl [OUT.lisp]   -- translate a module into a book
%%   escript erl_to_acl2.erl -e "2 + 2."           -- translate expressions
%%
%% From an Erlang shell:
%%   erl_to_acl2:expr_string("2 + 2.")   -> "(:binop + (:integer 2) (:integer 2))"
%%   erl_to_acl2:file("foo.erl", "foo.lisp")
-module(erl_to_acl2).
-export([main/1, file/2, expr_string/1, module_sexp/1, ast/1]).
-mode(compile).

main(["-e", Str]) ->
    io:format("~s~n", [expr_string(Str)]);
main([In]) ->
    Out = filename:rootname(In) ++ ".lisp",
    file(In, Out);
main([In, Out]) ->
    file(In, Out);
main(_) ->
    io:format(standard_error,
              "usage: escript erl_to_acl2.erl FILE.erl [OUT.lisp] | -e EXPRS~n", []),
    halt(1).

%% ---------------------------------------------------------------------------
%% Expressions

expr_string(Str) ->
    {ok, Toks, _} = erl_scan:string(Str),
    {ok, Exprs} = erl_parse:parse_exprs(Toks),
    string:join([sexp(ast(E)) || E <- Exprs], "\n").

%% ---------------------------------------------------------------------------
%% Modules

file(In, Out) ->
    {ok, Forms} = epp:parse_file(In, []),
    {Name, Sexp} = module_sexp(Forms),
    Const = "*" ++ atom_to_list(Name) ++ "-module*",
    Text = ["; Generated by erl_to_acl2 from ", filename:basename(In),
            ".  Do not edit.\n",
            "(in-package \"ACL2\")\n\n",
            "(defconst ", Const, "\n  '", Sexp, ")\n"],
    ok = file:write_file(Out, Text),
    io:format("wrote ~s (constant ~s)~n", [Out, Const]).

module_sexp(Forms) ->
    Name = hd([M || {attribute, _, module, M} <- Forms]),
    Exports = lists:append([Fs || {attribute, _, export, Fs} <- Forms]),
    Imports = lists:append([[{F, A, M} || {F, A} <- Fs]
                            || {attribute, _, import, {M, Fs}} <- Forms]),
    Funs = [{F, A, Cs} || {function, _, F, A, Cs} <- Forms],
    S = ["(:module ", sym(Name), "\n   ",
         "(", [["(", sym(F), " . ", integer_to_list(A), ")"] || {F, A} <- Exports], ")\n   ",
         "(", [["((", sym(F), " . ", integer_to_list(A), ") . ", sym(M), ")"]
               || {F, A, M} <- Imports], ")\n   (",
         [["\n    ((", sym(F), " . ", integer_to_list(A), ")\n     . ",
           sexp(clauses(Cs)), ")"] || {F, A, Cs} <- Funs],
         "))"],
    {Name, S}.

%% ---------------------------------------------------------------------------
%% AST normalization.  The result is a tree of {sx, ...} items:
%%   {kw, Name}  keyword        {sym, Atom} symbol (|...|)
%%   {op, Atom}  operator       {int, I}    integer
%%   list of items              (printed as a Lisp list)

ast({integer, _, I}) -> [{kw, integer}, {int, I}];
ast({char, _, C}) -> [{kw, integer}, {int, C}];
ast({float, _, _}) -> erlang:error(floats_not_supported);
ast({atom, _, A}) -> [{kw, atom}, {sym, A}];
ast({var, _, V}) -> [{kw, var}, {sym, V}];
ast({nil, _}) -> [{kw, nil}];
ast({string, _, S}) ->
    lists:foldr(fun(C, Acc) -> [{kw, cons}, [{kw, integer}, {int, C}], Acc] end,
                [{kw, nil}], S);
ast({cons, _, H, T}) -> [{kw, cons}, ast(H), ast(T)];
ast({tuple, _, Es}) -> [{kw, tuple}, ast_list(Es)];
ast({op, _, '!', A, B}) -> [{kw, send}, ast(A), ast(B)];
ast({op, _, Op, A, B}) -> [{kw, binop}, {op, Op}, ast(A), ast(B)];
ast({op, _, Op, A}) -> [{kw, unop}, {op, Op}, ast(A)];
ast({match, _, P, E}) -> [{kw, match}, ast(P), ast(E)];
ast({block, _, B}) -> [{kw, block}, body(B)];
ast({'if', _, Cs}) -> [{kw, 'if'}, clauses(Cs)];
ast({'case', _, E, Cs}) -> [{kw, 'case'}, ast(E), clauses(Cs)];
ast({'receive', _, Cs}) -> [{kw, 'receive'}, clauses(Cs)];
ast({'try', _, B, Of, Catch, After}) ->
    [{kw, 'try'}, body(B), clauses(Of), clauses(Catch), body(After)];
ast({'catch', _, E}) -> [{kw, 'catch'}, ast(E)];
ast({'fun', _, {clauses, Cs}}) -> [{kw, 'fun'}, clauses(Cs)];
ast({named_fun, _, Name, Cs}) -> [{kw, 'named-fun'}, {sym, Name}, clauses(Cs)];
ast({'fun', _, {function, F, A}}) when is_atom(F) ->
    [{kw, 'fun-ref'}, {sym, F}, {int, A}];
ast({'fun', _, {function, {atom, _, M}, {atom, _, F}, {integer, _, A}}}) ->
    [{kw, 'fun-ref-remote'}, {sym, M}, {sym, F}, {int, A}];
ast({call, _, {atom, _, F}, Args}) ->
    [{kw, 'call-local'}, {sym, F}, ast_list(Args)];
ast({call, _, {remote, _, {atom, _, M}, {atom, _, F}}, Args}) ->
    [{kw, 'call-remote'}, {sym, M}, {sym, F}, ast_list(Args)];
ast({call, _, F, Args}) ->
    [{kw, 'call-fun'}, ast(F), ast_list(Args)];
ast(Other) -> erlang:error({unsupported_construct, Other}).

%% Function arguments, tuple elements and clause patterns are erl_parse
%% Erlang lists; normalize them to parsed lists (:cons A (:cons B (:nil))).
ast_list(L) ->
    lists:foldr(fun(E, Acc) -> [{kw, cons}, ast(E), Acc] end, [{kw, nil}], L).

body(Es) -> [ast(E) || E <- Es].

clauses(Cs) -> [clause(C) || C <- Cs].

clause({clause, _, Pats, Guards, Body}) ->
    [{kw, clause}, ast_list(Pats), [body(G) || G <- Guards], body(Body)].

%% ---------------------------------------------------------------------------
%% Printing

sexp({kw, K}) -> [":", atom_to_list(K)];
sexp({sym, A}) -> sym(A);
sexp({op, A}) -> op(A);
sexp({int, I}) -> integer_to_list(I);
sexp(L) when is_list(L) -> ["(", lists:join(" ", [sexp(X) || X <- L]), ")"].

sym(A) ->
    S = atom_to_list(A),
    ["|", lists:flatmap(fun($|) -> "\\|"; ($\\) -> "\\\\"; (C) -> [C] end, S), "|"].

%% Operators print as plain ACL2 symbols (so `+` reads as ACL2::+, `div` as
%% ACL2::DIV) except those containing characters special to the Lisp reader.
op(A) ->
    S = atom_to_list(A),
    case lists:any(fun(C) -> lists:member(C, ":|;#'`,\"\\") end, S) of
        true -> sym(A);
        false -> S
    end.
