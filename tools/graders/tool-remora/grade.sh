#!/bin/bash
# Grader for tool-remora (paper gamboa-remora, ACL2 master 1d2b39a424).  Usage: grade.sh <work-dir>
# Prints one line per requirement (R1..R5: PASS / FAIL <reason> / MANUAL <what to inspect>) and a summary.
# Exit 0 iff every non-MANUAL requirement passes.  See CHECKLIST.md for the MANUAL items, NOTES.md for
# the interpretation and the validation.
set -u
WORK=$(cd "$1" && pwd)
G=$(cd "$(dirname "$0")" && pwd)
ACL2=/opt/acl2-master/saved_acl2
CERT=/opt/acl2-master/books/build/cert.pl
PY="python3 -I $G/check.py"
T=$(mktemp -d /tmp/grade-tool-remora-XXXXXX)
W=$T/work
cp -r "$WORK" "$W"
find "$W" \( -name '*.cert' -o -name '*.cert.out' -o -name '*.port' -o -name '*.fasl' -o -name '*.lx64fsl' \
  -o -name '*.pcert0' -o -name '*.pcert1' -o -name '*.acl2x' -o -name '*.cert.time' \) -delete
echo "grading copy: $T"
declare -A RES
say() { RES[$1]="$2"; }

# ------------------------------------------------------------------ banned events
B=$($PY banned "$W")
if [ -n "$B" ]; then
  echo "BANNED events:"; echo "$B"
  for r in 1 2 3 4 5; do echo "R$r FAIL banned event in the model's files (see above)"; done
  echo "SUMMARY: FAIL (banned events)"; exit 1
fi

# ------------------------------------------------------------------ R5: certify every model book
$PY books "$W" > $T/books.txt
mapfile -t BOOKS < $T/books.txt
CERTFAIL=()
if [ ${#BOOKS[@]} -gt 0 ]; then
  (cd "$W" && timeout 6h perl $CERT --acl2 $ACL2 -j 4 -k "${BOOKS[@]}") > $T/cert-model.log 2>&1
  for b in "${BOOKS[@]}"; do [ -f "$W/${b%.lisp}.cert" ] || CERTFAIL+=("$b"); done
fi
if [ ${#BOOKS[@]} = 0 ]; then say 5 "FAIL no .lisp books in /work"
elif [ ${#CERTFAIL[@]} = 0 ]; then say 5 "PASS (${#BOOKS[@]} books: ${BOOKS[*]})"
else say 5 "FAIL not certified: ${CERTFAIL[*]} (see $T/cert-model.log; CHECKLIST R5 if one is not meant as a book)"; fi
certified() { [ -f "$W/${1%.lisp}.cert" ]; }

# ------------------------------------------------------------------ grader books
Z=$W/zz-grader
mkdir -p $Z
cp $G/grade-r*.lisp $Z/
printf '; grader books: Remora package only\n(include-book "kestrel/remora/portcullis" :dir :system)\n' > $Z/cert.acl2
THMS="propagate-not-reserrp-cells-at-depth-in-expr-value-list-when-vector eval-app-list-when-primop-binary-and-bases
eval-app-when-funval-is-binary-op undo-expr-value-with-nonempty-dims-3 eval-app-when-funval-is-binary-op-fully"
HELPERS="pairwise-curry-binary-fn pairwise-curry-binary-x-fn pairwise-binary-args-fn get-cells-from-expr-value
expr-is-nested-vectors-of-base-values list-of-primop-int-binary list-of-base-values"
gen_model_book() {  # $@ = model books to include
  { echo '(in-package "ACL2")'; echo '; generated by grade.sh: includes the model books'
    for b in "$@"; do echo "(include-book \"../${b%.lisp}\")"; done; } > $Z/grader-model.lisp
  rm -f $Z/grader-model.cert
  (cd $Z && perl $CERT --acl2 $ACL2 grader-model.lisp) > $T/cert-grader-model.log 2>&1
  [ -f $Z/grader-model.cert ]
}
OKB=(); for b in "${BOOKS[@]}"; do certified "$b" && OKB+=("$b"); done
MODEL_OK=no
if [ ${#OKB[@]} -gt 0 ] && gen_model_book "${OKB[@]}"; then MODEL_OK=yes
else
  mapfile -t DEF < <($PY defines "$W" $THMS $HELPERS)
  OKD=(); for b in "${DEF[@]}"; do certified "$b" && OKD+=("$b"); done
  [ ${#OKD[@]} -gt 0 ] && gen_model_book "${OKD[@]}" && MODEL_OK=yes
fi
cert_grader() { rm -f $Z/$1.cert; (cd $Z && timeout 2h perl $CERT --acl2 $ACL2 "$1.lisp") > $T/cert-$1.log 2>&1; [ -f $Z/$1.cert ]; }

# ------------------------------------------------------------------ R1: helper functions
if [ $MODEL_OK = no ]; then
  say 1 "FAIL the model's books cannot be included together with the interpreter (see $T/cert-grader-model.log)"
elif ! cert_grader grade-r1; then
  say 1 "FAIL some helper function is missing, constrained only, or has the wrong arity (see $T/cert-grade-r1.log)"
elif ! cert_grader grade-r1v; then
  say 1 "FAIL helpers defined, but they do not mean what the paper says on the Sec. 2 example [1 2] + [[1 2] [3 4]] (see $T/cert-grade-r1v.log; grade-r1v.lisp lists the checks)"
else
  say 1 "PASS (seven helpers defined with the paper's arities; on [1 2] + [[1 2] [3 4]] the hypotheses of the R2 theorems hold and the right-hand side of the final theorem gives [[2 3] [5 6]])"
fi

# ------------------------------------------------------------------ R2: the five theorems
if [ $MODEL_OK = no ]; then
  say 2 "FAIL the model's books cannot be included together with the interpreter (see $T/cert-grader-model.log)"
else
  st=PASS; msgs=(); i=0
  for name in $THMS; do
    i=$((i+1))
    if [ $i = 4 ]; then
      if cert_grader grade-r2-4a || cert_grader grade-r2-4b; then ok=1; else ok=0; fi
    else
      if cert_grader grade-r2-$i; then ok=1; else ok=0; fi
    fi
    [ $ok = 1 ] && { msgs+=("$name: verbatim (:by)"); continue; }
    REP=$($PY thm "$W" "$G/targets.lisp" "$name")
    first=$(echo "$REP" | head -1); rd=$(echo "$REP" | tail -1)
    case "$first" in
      MISSING) st=FAIL; msgs+=("$name: MISSING");;
      SAME*)   st=FAIL; msgs+=("$name: statement as printed but :by fails (not proved, local, or not over the interpreter's functions; see $T/cert-grade-r2-$i*.log)");;
      DIFF*)
        if [ "$rd" = README:yes ]; then
          [ $st = PASS ] && st=MANUAL
          msgs+=("$name: CHANGED, listed in README.md; review the change (CHECKLIST R2):
$(echo "$REP" | sed '1d;$d' | sed 's/^/      /')")
        else
          st=FAIL; msgs+=("$name: CHANGED and not listed in README.md:
$(echo "$REP" | sed '1d;$d' | sed 's/^/      /')")
        fi;;
    esac
  done
  say 2 "$st $(printf '%s; ' "${msgs[@]}")"
fi

# ------------------------------------------------------------------ R3: commutativity corollary (own statement)
CAND=$($PY comm "$W" | tr '\n' ' ')
say 3 "MANUAL find the commutativity corollary in README.md / the books and judge it per CHECKLIST R3 (candidates found automatically: ${CAND:-none})"

# ------------------------------------------------------------------ R4: examples.lisp
if cert_grader grade-r4; then V="grader's own Sec. 2 evaluations (grade-r4) pass on the interpreter"
else V="WARNING: grader's own Sec. 2 evaluations (grade-r4) FAIL on the interpreter (see $T/cert-grade-r4.log) - a grader/interpreter problem, not the model's"; fi
EX=$($PY examples "$W")
if [[ $EX == FAIL* ]]; then say 4 "$EX ($V)"
elif ! certified examples.lisp; then say 4 "FAIL /work/examples.lisp does not certify ($V)"
else say 4 "MANUAL examples.lisp certifies, ${EX#OK }; check it evaluates the three Sec. 2 examples per CHECKLIST R4 ($V)"; fi

# ------------------------------------------------------------------ report
fail=0; man=0
for r in 1 2 3 4 5; do
  echo "R$r ${RES[$r]}"
  case "${RES[$r]}" in FAIL*) fail=$((fail+1));; MANUAL*) man=$((man+1));; esac
done
if [ $fail = 0 ]; then echo "SUMMARY: PASS ($man MANUAL item(s) to inspect, see CHECKLIST.md)"; exit 0
else echo "SUMMARY: FAIL ($fail requirement(s) failed, $man MANUAL)"; exit 1; fi
